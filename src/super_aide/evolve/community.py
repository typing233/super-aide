MIN_SNIPPET = 12
_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_SAFE_EMAIL = re.compile(r"@(example\.(com|org)|users\.noreply\.github\.com|anthropic\.com|localhost)", re.IGNORECASE)
_PHONE = re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")
