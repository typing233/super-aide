def upstream() -> str:
    return update.release_info().get("repo") or DEFAULT_REPO


def added_lines(patch: str) -> str:
    return "\n".join(line[1:] for line in patch.splitlines() if line.startswith("+") and not line.startswith("+++"))


def evidence_snippets(evidence_dir: Path) -> list[str]:
    """证据里可能是隐私的原文：问题、屏幕上的文字、窗口标题、你说的原因或建议（按行，12 个字以上）。"""
    texts: list[str] = []
    raw = evidence_dir / "raw.json"
    try:
        data = json.loads(raw.read_text(encoding="utf-8")) if raw.exists() else {}
    except (OSError, ValueError):
        data = {}
    for turn in data.get("record", []):
        situation = turn.get("situation") or {}
        texts += [turn.get("question", ""), situation.get("text", ""), situation.get("title", ""),
                  situation.get("errors", "")]
    texts += [t.get("text", "") for t in data.get("trouble", [])]
    suggestion = evidence_dir / "建议.md"
    if suggestion.exists():
        texts.append(suggestion.read_text(encoding="utf-8"))
    snippets = set()
    for text in texts:
        for line in re.split(r"[\n。！？；]", text or ""):
            line = " ".join(line.split())
            if len(line) >= MIN_SNIPPET:
                snippets.add(line)
    return sorted(snippets)


def privacy_scan(patch: str, snippets: list[str]) -> list[str]:
    """补丁新增的内容里疑似个人信息的地方（空 = 没发现）。"""
    added = added_lines(patch)
    flat = " ".join(added.split())
    hits = []
    home = os.path.expanduser("~")
    user = os.path.basename(home)
    if user and re.search(rf"Users[\\/]+{re.escape(user)}\b", added, re.IGNORECASE):
        hits.append(f"本机的用户目录（{home}）")
    computer = os.environ.get("COMPUTERNAME", "")
    if len(computer) >= 4 and re.search(rf"\b{re.escape(computer)}\b", added, re.IGNORECASE):
        hits.append(f"计算机名（{computer}）")
    hits += [f"邮箱 {m}" for m in sorted(set(_EMAIL.findall(added))) if not _SAFE_EMAIL.search(m)][:3]
    hits += [f"手机号 {m[:3]}****{m[-4:]}" for m in sorted(set(_PHONE.findall(added)))][:3]
    hits += [f"像令牌的字符串 {m[:6]}…" for m in sorted(set(_TOKEN.findall(added)))][:3]
    hits += [f"证据里的原文：{s[:30]}…" for s in snippets if s in flat][:5]
    return hits


def pr_body(job, choice: str, marker: str) -> str:
    r = job.result
    return "\n".join([
        f"**{r.get('title_zh', '')}** / {r.get('title_en', '')}", "",
        r.get("summary_zh", ""), "", r.get("summary_en", ""), "",
        f"- 测试 / Tests: {r.get('tests', '')}",
        f"- 风险 / Risk: {r.get('risk', '')}",
        f"- 本地已稳定运行 / Running locally since: {job.version}", "",
        f"由超级助手自我改进生成（{choice}），在提交者的电脑上通过了测试和独立复核。",
        f"Generated by Super Aide self-improvement ({choice}); passed the test suite and an independent review "
        "on the contributor's machine.", "",
        f"<sub>{marker}</sub>",
    ])


def apply_upstream(gh: GitHub, repo: str, base: str, patch: str) -> tuple[dict[str, str | None], list[str]]:
    """把补丁套到主版本 base 那个提交的文件上。返回 (路径 → 新内容, 套不上的文件)。"""
    out: dict[str, str | None] = {}
    failed = []
    for fp in patching.parse(patch):
        if fp.binary:
            failed.append(fp.path)
            continue
        current = gh.file_at(repo, fp.path, base)
        try:
            if fp.created:
                if current is not None:
                    raise patching.PatchError("主版本已经有这个文件了")
                out[fp.path] = "".join(patching.apply_to_text([], fp))
            elif current is None:
                raise patching.PatchError("主版本里没有这个文件")
            elif fp.deleted:
                out[fp.path] = None
            else:
                out[fp.path] = "".join(patching.apply_to_text(current.splitlines(keepends=True), fp))
        except patching.PatchError:
            failed.append(fp.path)
    return out, failed


def already_included(gh: GitHub, repo: str, base: str, patch: str) -> bool:
    """主版本 base 那个提交里已经有这次的改动了（每个文件都能把补丁反着套上）：不用再提交。"""
    parsed = patching.parse(patch)
    if not parsed:
        return False
    for fp in parsed:
        if fp.binary:
            return False
        current = gh.file_at(repo, fp.path, base)
        if fp.deleted:
            if current is not None:
                return False
            continue
        if current is None:
            return False
        try:
            patching.apply_to_text(current.splitlines(keepends=True), fp, reverse=True)
        except patching.PatchError:
            return False
    return True


def compile_check(files: dict[str, str | None]) -> list[str]:
    bad = []
    for path, text in files.items():
        if text is not None and path.endswith(".py"):
            try:
                compile(text, path, "exec")
            except SyntaxError as e:
                bad.append(f"{path}:{e.lineno}: {e.msg}")
    return bad
